CREATE VIEW v_active_tickets_summary AS
SELECT 
    t.tenant_id,
    t.company_name,
    COUNT(DISTINCT i.incident_id) as active_incidents,
    COUNT(DISTINCT p.problem_id) as active_problems,
    COUNT(DISTINCT c.change_id) as active_changes,
    COUNT(DISTINCT sr.request_id) as active_requests
FROM tenants t
LEFT JOIN incidents i ON t.tenant_id = i.tenant_id AND i.status NOT IN ('closed', 'cancelled')
LEFT JOIN problems p ON t.tenant_id = p.tenant_id AND p.status NOT IN ('closed', 'cancelled')
LEFT JOIN changes c ON t.tenant_id = c.tenant_id AND c.status NOT IN ('completed', 'cancelled', 'rejected')
LEFT JOIN service_requests sr ON t.tenant_id = sr.tenant_id AND sr.status NOT IN ('closed', 'cancelled')
WHERE t.is_active = TRUE
GROUP BY t.tenant_id, t.company_name;
