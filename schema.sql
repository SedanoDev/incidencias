DROP DATABASE IF EXISTS itil_ticketing_saas;

CREATE DATABASE itil_ticketing_saas CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE itil_ticketing_saas;

CREATE TABLE tenants (
    tenant_id INT PRIMARY KEY AUTO_INCREMENT,
    tenant_code VARCHAR(50) UNIQUE NOT NULL,
    company_name VARCHAR(200) NOT NULL,
    subdomain VARCHAR(100) UNIQUE,
    custom_domain VARCHAR(200) UNIQUE,
    subscription_plan ENUM('free', 'basic', 'professional', 'enterprise', 'custom') DEFAULT 'basic',
    subscription_status ENUM('trial', 'active', 'suspended', 'cancelled', 'expired') DEFAULT 'trial',
    trial_start_date DATE,
    trial_end_date DATE,
    subscription_start_date DATE,
    subscription_end_date DATE,
    max_users INT DEFAULT 10,
    max_tickets_per_month INT DEFAULT 1000,
    max_storage_gb INT DEFAULT 10,
    features JSON,
    billing_email VARCHAR(100),
    contact_name VARCHAR(100),
    contact_email VARCHAR(100),
    contact_phone VARCHAR(20),
    address TEXT,
    country VARCHAR(100),
    timezone VARCHAR(50) DEFAULT 'UTC',
    language VARCHAR(10) DEFAULT 'es',
    currency VARCHAR(3) DEFAULT 'EUR',
    logo_url VARCHAR(500),
    custom_branding JSON,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL,
    INDEX idx_subdomain (subdomain),
    INDEX idx_status (subscription_status),
    INDEX idx_active (is_active)
);

CREATE TABLE tenant_settings (
    setting_id INT PRIMARY KEY AUTO_INCREMENT,
    tenant_id INT NOT NULL,
    setting_key VARCHAR(100) NOT NULL,
    setting_value TEXT,
    setting_type ENUM('string', 'number', 'boolean', 'json') DEFAULT 'string',
    description TEXT,
    updated_by INT,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE,
    UNIQUE KEY unique_tenant_setting (tenant_id, setting_key),
    INDEX idx_tenant (tenant_id)
);

CREATE TABLE tenant_usage (
    usage_id INT PRIMARY KEY AUTO_INCREMENT,
    tenant_id INT NOT NULL,
    usage_month DATE NOT NULL,
    users_count INT DEFAULT 0,
    tickets_created INT DEFAULT 0,
    storage_used_gb DECIMAL(10,2) DEFAULT 0,
    api_calls INT DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE,
    UNIQUE KEY unique_tenant_month (tenant_id, usage_month),
    INDEX idx_tenant (tenant_id)
);

CREATE TABLE users (
    user_id INT PRIMARY KEY AUTO_INCREMENT,
    tenant_id INT NOT NULL,
    username VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    phone VARCHAR(20),
    department_id INT,
    role ENUM('end_user', 'technician', 'manager', 'admin', 'tenant_admin') DEFAULT 'end_user',
    is_active BOOLEAN DEFAULT TRUE,
    last_login_at TIMESTAMP NULL,
    password_changed_at TIMESTAMP NULL,
    failed_login_attempts INT DEFAULT 0,
    locked_until TIMESTAMP NULL,
    must_change_password BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE,
    UNIQUE KEY unique_tenant_username (tenant_id, username),
    UNIQUE KEY unique_tenant_email (tenant_id, email),
    INDEX idx_tenant (tenant_id),
    INDEX idx_email (email),
    INDEX idx_department (department_id),
    INDEX idx_active (tenant_id, is_active)
);

CREATE TABLE departments (
    department_id INT PRIMARY KEY AUTO_INCREMENT,
    tenant_id INT NOT NULL,
    department_name VARCHAR(100) NOT NULL,
    department_code VARCHAR(20) NOT NULL,
    manager_id INT,
    location VARCHAR(100),
    cost_center VARCHAR(50),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE,
    UNIQUE KEY unique_tenant_dept_code (tenant_id, department_code),
    INDEX idx_tenant (tenant_id),
    INDEX idx_manager (manager_id)
);

CREATE TABLE teams (
    team_id INT PRIMARY KEY AUTO_INCREMENT,
    tenant_id INT NOT NULL,
    team_name VARCHAR(100) NOT NULL,
    team_type ENUM('support', 'development', 'infrastructure', 'security', 'network') NOT NULL,
    team_lead_id INT,
    department_id INT,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE,
    FOREIGN KEY (team_lead_id) REFERENCES users(user_id),
    FOREIGN KEY (department_id) REFERENCES departments(department_id),
    INDEX idx_tenant (tenant_id),
    INDEX idx_team_type (team_type)
);

CREATE TABLE team_members (
    team_member_id INT PRIMARY KEY AUTO_INCREMENT,
    tenant_id INT NOT NULL,
    team_id INT NOT NULL,
    user_id INT NOT NULL,
    role_in_team ENUM('member', 'lead', 'backup') DEFAULT 'member',
    joined_date DATE NOT NULL,
    left_date DATE,
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE,
    FOREIGN KEY (team_id) REFERENCES teams(team_id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    UNIQUE KEY unique_active_member (tenant_id, team_id, user_id, left_date),
    INDEX idx_tenant (tenant_id)
);

CREATE TABLE ci_types (
    ci_type_id INT PRIMARY KEY AUTO_INCREMENT,
    tenant_id INT NULL,
    type_name VARCHAR(50) NOT NULL,
    type_category ENUM('hardware', 'software', 'network', 'database', 'service', 'documentation') NOT NULL,
    description TEXT,
    is_custom BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_tenant (tenant_id),
    UNIQUE KEY unique_type_name (tenant_id, type_name)
);

CREATE TABLE configuration_items (
    ci_id INT PRIMARY KEY AUTO_INCREMENT,
    tenant_id INT NOT NULL,
    ci_number VARCHAR(50) NOT NULL,
    ci_name VARCHAR(100) NOT NULL,
    ci_type_id INT NOT NULL,
    status ENUM('active', 'inactive', 'retired', 'under_maintenance', 'planned') DEFAULT 'active',
    owner_id INT,
    managed_by_team_id INT,
    location VARCHAR(100),
    serial_number VARCHAR(100),
    asset_tag VARCHAR(50),
    manufacturer VARCHAR(100),
    model VARCHAR(100),
    purchase_date DATE,
    warranty_expiry DATE,
    cost DECIMAL(10,2),
    ip_address VARCHAR(45),
    hostname VARCHAR(100),
    operating_system VARCHAR(100),
    version VARCHAR(50),
    description TEXT,
    criticality ENUM('low', 'medium', 'high', 'critical') DEFAULT 'medium',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE,
    FOREIGN KEY (ci_type_id) REFERENCES ci_types(ci_type_id),
    FOREIGN KEY (owner_id) REFERENCES users(user_id),
    FOREIGN KEY (managed_by_team_id) REFERENCES teams(team_id),
    UNIQUE KEY unique_tenant_ci_number (tenant_id, ci_number),
    INDEX idx_tenant (tenant_id),
    INDEX idx_status (tenant_id, status),
    INDEX idx_ci_type (ci_type_id),
    INDEX idx_criticality (criticality)
);

CREATE TABLE ci_relationships (
    relationship_id INT PRIMARY KEY AUTO_INCREMENT,
    tenant_id INT NOT NULL,
    parent_ci_id INT NOT NULL,
    child_ci_id INT NOT NULL,
    relationship_type ENUM('depends_on', 'part_of', 'connected_to', 'uses', 'hosted_on', 'runs_on') NOT NULL,
    description TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE,
    FOREIGN KEY (parent_ci_id) REFERENCES configuration_items(ci_id) ON DELETE CASCADE,
    FOREIGN KEY (child_ci_id) REFERENCES configuration_items(ci_id) ON DELETE CASCADE,
    INDEX idx_tenant (tenant_id),
    INDEX idx_parent (parent_ci_id),
    INDEX idx_child (child_ci_id)
);

CREATE TABLE categories (
    category_id INT PRIMARY KEY AUTO_INCREMENT,
    tenant_id INT NULL,
    category_name VARCHAR(100) NOT NULL,
    parent_category_id INT,
    category_type ENUM('incident', 'problem', 'change', 'service_request') NOT NULL,
    description TEXT,
    is_active BOOLEAN DEFAULT TRUE,
    is_custom BOOLEAN DEFAULT FALSE,
    FOREIGN KEY (parent_category_id) REFERENCES categories(category_id),
    INDEX idx_tenant (tenant_id),
    INDEX idx_category_type (category_type),
    INDEX idx_parent (parent_category_id),
    UNIQUE KEY unique_category_name (tenant_id, category_name, category_type)
);

CREATE TABLE priority_matrix (
    priority_id INT PRIMARY KEY AUTO_INCREMENT,
    tenant_id INT NULL,
    priority_name VARCHAR(20) NOT NULL,
    priority_level INT NOT NULL,
    impact ENUM('low', 'medium', 'high', 'critical') NOT NULL,
    urgency ENUM('low', 'medium', 'high', 'critical') NOT NULL,
    response_time_hours INT NOT NULL,
    resolution_time_hours INT NOT NULL,
    description TEXT,
    is_custom BOOLEAN DEFAULT FALSE,
    INDEX idx_tenant (tenant_id),
    UNIQUE KEY unique_impact_urgency (tenant_id, impact, urgency)
);

CREATE TABLE incidents (
    incident_id INT PRIMARY KEY AUTO_INCREMENT,
    tenant_id INT NOT NULL,
    incident_number VARCHAR(50) NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    reported_by INT NOT NULL,
    reported_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    category_id INT,
    subcategory_id INT,
    affected_ci_id INT,
    impact ENUM('low', 'medium', 'high', 'critical') NOT NULL,
    urgency ENUM('low', 'medium', 'high', 'critical') NOT NULL,
    priority_id INT,
    status ENUM('new', 'assigned', 'in_progress', 'on_hold', 'resolved', 'closed', 'cancelled') DEFAULT 'new',
    assigned_to INT,
    assigned_team_id INT,
    resolution_code VARCHAR(100),
    resolution_notes TEXT,
    workaround TEXT,
    related_problem_id INT,
    related_change_id INT,
    escalation_level INT DEFAULT 0,
    reopened_count INT DEFAULT 0,
    sla_breach BOOLEAN DEFAULT FALSE,
    target_resolution_date TIMESTAMP NULL,
    resolved_date TIMESTAMP NULL,
    closed_date TIMESTAMP NULL,
    closed_by INT,
    closure_category VARCHAR(100),
    customer_satisfaction_rating INT CHECK (customer_satisfaction_rating BETWEEN 1 AND 5),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE,
    FOREIGN KEY (reported_by) REFERENCES users(user_id),
    FOREIGN KEY (category_id) REFERENCES categories(category_id),
    FOREIGN KEY (affected_ci_id) REFERENCES configuration_items(ci_id),
    FOREIGN KEY (priority_id) REFERENCES priority_matrix(priority_id),
    FOREIGN KEY (assigned_to) REFERENCES users(user_id),
    FOREIGN KEY (assigned_team_id) REFERENCES teams(team_id),
    FOREIGN KEY (closed_by) REFERENCES users(user_id),
    UNIQUE KEY unique_tenant_incident_number (tenant_id, incident_number),
    INDEX idx_tenant (tenant_id),
    INDEX idx_status (tenant_id, status),
    INDEX idx_priority (priority_id),
    INDEX idx_assigned (assigned_to),
    INDEX idx_reported_date (tenant_id, reported_date),
    INDEX idx_sla_breach (tenant_id, sla_breach)
);

