CREATE TABLE known_errors (
    kedb_id INT PRIMARY KEY AUTO_INCREMENT,
    tenant_id INT NOT NULL,
    kedb_number VARCHAR(50) NOT NULL,
    problem_id INT NOT NULL,
    title VARCHAR(200) NOT NULL,
    error_description TEXT NOT NULL,
    symptoms TEXT NOT NULL,
    root_cause TEXT NOT NULL,
    workaround TEXT,
    permanent_solution TEXT,
    affected_cis TEXT,
    occurrence_frequency ENUM('rare', 'occasional', 'frequent', 'very_frequent') DEFAULT 'occasional',
    severity ENUM('low', 'medium', 'high', 'critical') NOT NULL,
    status ENUM('active', 'resolved', 'archived') DEFAULT 'active',
    created_by INT NOT NULL,
    created_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    resolution_date TIMESTAMP NULL,
    times_referenced INT DEFAULT 0,
    FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id) ON DELETE CASCADE,
    FOREIGN KEY (problem_id) REFERENCES problems(problem_id),
    FOREIGN KEY (created_by) REFERENCES users(user_id),
    UNIQUE KEY unique_tenant_kedb_number (tenant_id, kedb_number),
    INDEX idx_tenant (tenant_id),
    INDEX idx_status (tenant_id, status),
    INDEX idx_severity (severity),
    FULLTEXT idx_search (title, error_description, symptoms)
);

CREATE TABLE incident_problem_relations (
    relation_id INT PRIMARY KEY AUTO_INCREMENT,
